# MySQL / MariaDB


def mysql(args):
    query = (
        "SELECT TO_BASE64(t.name), TO_BASE64(t.description), TO_BASE64(COALESCE(t.example, '')), "
        "TO_BASE64(c.name) FROM mysql.help_topic t "
        "JOIN mysql.help_category c ON c.help_category_id = t.help_category_id"
    )
    rows = subprocess.run(
        ["docker", "exec", args.mysql_container, "mariadb", f"-u{args.mysql_user}",
         f"-p{args.mysql_password}", "-N", "-B", "-e", query],
        check=True, capture_output=True, text=True,
    ).stdout
    version = subprocess.run(
        ["docker", "exec", args.mysql_container, "mariadb", f"-u{args.mysql_user}",
         f"-p{args.mysql_password}", "-N", "-B", "-e", "SELECT VERSION()"],
        check=True, capture_output=True, text=True,
    ).stdout.strip()

    def decode(cell):
        return base64.b64decode(cell.replace("\\n", "")).decode("utf-8", errors="replace")

    entries = []
    for line in rows.splitlines():
        if not line.strip():
            continue
        name, description, example, category = (decode(c) for c in line.split("\t"))
        syntax_match = re.search(r"Syntax\n-+\n(.*?)(?:\n\n[A-Z][A-Za-z ]+\n-+\n|\Z)", description, re.S)
        if not syntax_match:
            continue
        syntax_block = syntax_match.group(1).strip()
        body_match = re.search(r"Description\n-+\n(.*)", description, re.S)
        body = body_match.group(1).strip() if body_match else ""
        # The help text is plain text with ASCII result tables; fence the
        # examples so they survive markdown rendering, and link the URL line.
        url = ""
        url_match = re.search(r"\n\s*URL: (\S+)\s*$", body)
        if url_match:
            url = url_match.group(1)
            body = body[: url_match.start()].rstrip()
        example_text = example.strip()
        example_match = re.search(r"\n\s*Examples?\n-+\n", body)
        if example_match:
            example_text = (body[example_match.end():].strip() + "\n\n" + example_text).strip()
            body = body[: example_match.start()].rstrip()
        parts = [f"*{category}*"]
        if body:
            parts.append(body)
        if example_text:
            parts.append(f"```sql\n{example_text}\n```")
        if url:
            parts.append(f"[{url}]({url})")
        documentation = "\n\n".join(parts)

        # A topic can list several forms (`CONCAT(str1,str2,...)`, `SUBSTR(str,pos)`,
        # `SUBSTR(str FROM pos)`); each parseable form becomes an overload.
        forms = [parse_call_syntax(line) for line in syntax_block.splitlines()]
        forms = [f for f in forms if f and f[0].upper() == name.upper()]
        if not forms:
            continue
        for _, parameters in forms:
            entries.append({
                "name": name,
                "parameters": parameters,
                "return_type": "",
                "documentation": documentation,
            })
    emit("mysql", entries, f"mysql.help_topic on MariaDB {version}")


