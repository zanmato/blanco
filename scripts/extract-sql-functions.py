# PostgreSQL

PG_EXCLUDED_DOC_PATTERNS = [
    r"^implementation of .* operator$",
    r"I/O",
    r"^less-equal-greater$",
    r"^hash$",
    r"^smaller of two$",
    r"^larger of two$",
    r"support",
    r"^aggregate .* function$",
    r"for use by pg_upgrade",
    r"^\(internal\)$",
    r"internal use",
    r"^planner support",
]
PG_EXCLUDED_NAME_SUFFIXES = (
    "_in", "_out", "_recv", "_send", "_cmp", "_lt", "_le", "_gt", "_ge", "_eq", "_ne",
    "_support", "_sel", "_joinsel", "_typmod_in", "_typmod_out", "_subtype_diff", "_hash",
    "_hash_extended", "_sortsupport", "_options", "_restrict", "_transfn", "_finalfn",
    "_combine", "_serialize", "_deserialize", "_accum", "_worker", "_inv", "_analyze",
    "_larger", "_smaller", "_transfn_internal",
)
PG_EXCLUDED_NAME_PREFIXES = (
    "_", "binary_upgrade", "RI_FKey", "gin_", "gist_", "brin_", "spg_", "amvalidate", "aclitem",
    "bt", "hash", "tsm_", "ts_debug",
)
PG_INTERNAL_TYPES = re.compile(
    r"\b(internal|cstring|opaque|trigger|event_trigger|language_handler|fdw_handler|"
    r"index_am_handler|tsm_handler|table_am_handler)\b"
)


def postgres(args):
    env = dict(os.environ, PGPASSWORD=args.pg_password)
    query = """
        SELECT p.proname,
               pg_get_function_arguments(p.oid),
               pg_get_function_result(p.oid),
               coalesce(obj_description(p.oid, 'pg_proc'), ''),
               p.prokind
        FROM pg_proc p
        JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'pg_catalog' AND p.prokind IN ('f', 'a', 'w')
        ORDER BY 1, 2
    """
    result = subprocess.run(
        [
            "psql", "-h", args.pg_host, "-p", str(args.pg_port), "-U", args.pg_user,
            "-d", args.pg_database, "-At", "-F", "\x01", "-R", "\x02", "-c", query,
        ],
        env=env, check=True, capture_output=True, text=True,
    )
    version = subprocess.run(
        ["psql", "-h", args.pg_host, "-p", str(args.pg_port), "-U", args.pg_user,
         "-d", args.pg_database, "-At", "-c", "SHOW server_version"],
        env=env, check=True, capture_output=True, text=True,
    ).stdout.strip()

    entries = []
    for record in result.stdout.split("\x02"):
        record = record.strip("\n")
        if not record:
            continue
        name, arguments, return_type, doc, kind = record.split("\x01")
        if name.startswith(PG_EXCLUDED_NAME_PREFIXES) or name.endswith(PG_EXCLUDED_NAME_SUFFIXES):
            continue
        if any(re.search(p, doc, re.I) for p in PG_EXCLUDED_DOC_PATTERNS):
            continue
        if PG_INTERNAL_TYPES.search(arguments) or PG_INTERNAL_TYPES.search(return_type):
            continue
        parameters = [
            p for p in split_top_level(arguments)
            if not p.startswith("OUT ")
        ]
        kind_note = {"a": "Aggregate function", "w": "Window function"}.get(kind)
        documentation = doc[:1].upper() + doc[1:] if doc else ""
        if kind_note:
            documentation = f"{documentation}\n\n*{kind_note}*" if documentation else f"*{kind_note}*"
        entries.append({
            "name": name,
            "parameters": parameters,
            "return_type": return_type,
            "documentation": documentation,
        })
    emit("postgres", entries, f"pg_catalog.pg_proc on PostgreSQL {version}")


