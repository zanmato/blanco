# SQLite (lint only)


def sqlite(args):
    connection = sqlite3.connect(":memory:")
    builtin = {
        row[0].lower()
        for row in connection.execute(
            "SELECT DISTINCT name FROM pragma_function_list WHERE builtin = 1"
        )
    }
    path = os.path.join(OUT_DIR, "sqlite.rs")
    with open(path) as handle:
        curated = set(re.findall(r'name: "([^"]+)"', handle.read()))
    curated = {name.lower() for name in curated}
    missing = sorted(builtin - curated)
    print(f"sqlite {sqlite3.sqlite_version}: {len(builtin)} built-ins, {len(curated)} curated")
    if missing:
        print("missing from sqlite.rs: " + ", ".join(missing))
    unknown = sorted(curated - builtin)
    if unknown:
        print("curated but not reported by pragma_function_list (extensions or SQL-only forms): "
              + ", ".join(unknown))


