def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("dialect", choices=["postgres", "mysql", "clickhouse", "sqlite", "all"])
    parser.add_argument("--pg-host", default="127.0.0.1")
    parser.add_argument("--pg-port", default=5488, type=int)
    parser.add_argument("--pg-user", default="blanco")
    parser.add_argument("--pg-password", default="blanco")
    parser.add_argument("--pg-database", default="blanco")
    parser.add_argument("--mysql-container", default="blanco-mysqltestdb-1")
    parser.add_argument("--mysql-user", default="root")
    parser.add_argument("--mysql-password", default="blanco")
    parser.add_argument("--ch-host", default="127.0.0.1")
    parser.add_argument("--ch-port", default=8124, type=int)
    parser.add_argument("--ch-user", default="blanco")
    parser.add_argument("--ch-password", default="blanco")
    args = parser.parse_args()

    steps = {"postgres": postgres, "mysql": mysql, "clickhouse": clickhouse, "sqlite": sqlite}
    selected = steps.keys() if args.dialect == "all" else [args.dialect]
    failed = False
    for name in selected:
        try:
            steps[name](args)
        except Exception as error:  # report every dialect before failing
            failed = True
            print(f"{name}: failed: {error}", file=sys.stderr)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
