# ClickHouse


def clickhouse(args):
    def query(sql):
        request = urllib.request.Request(
            f"http://{args.ch_host}:{args.ch_port}/",
            data=sql.encode(),
            headers={"X-ClickHouse-User": args.ch_user, "X-ClickHouse-Key": args.ch_password},
        )
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read().decode()

    version = query("SELECT version() FORMAT TSVRaw").strip()
    rows = [
        json.loads(line)
        for line in query(
            "SELECT name, is_aggregate, alias_to, description, syntax, arguments, "
            "returned_value, categories FROM system.functions WHERE origin = 'System' "
            "FORMAT JSONEachRow"
        ).splitlines()
        if line.strip()
    ]
    by_name = {row["name"]: row for row in rows}

    entries = []
    for row in rows:
        name = row["name"]
        if name.startswith("_"):
            continue
        source = by_name.get(row["alias_to"]) if row["alias_to"] else row
        source = source or row
        parsed = parse_call_syntax(source["syntax"]) if source["syntax"] else None
        parameters = parsed[1] if parsed else []
        description = trim_paragraphs(source["description"].strip(), 1200)
        parts = []
        if row["alias_to"]:
            parts.append(f"Alias of `{row['alias_to']}`.")
        if description:
            parts.append(description)
        if source["arguments"].strip():
            parts.append("**Arguments**\n\n" + source["arguments"].strip())
        if source["returned_value"].strip():
            parts.append("**Returns** " + source["returned_value"].strip())
        notes = []
        if row["is_aggregate"]:
            notes.append("Aggregate function")
        if source["categories"].strip():
            notes.append(source["categories"].strip())
        if notes:
            parts.append("*" + ", ".join(notes) + "*")
        entries.append({
            "name": name,
            "parameters": parameters,
            "return_type": "",
            "documentation": "\n\n".join(parts),
        })
    emit("clickhouse", entries, f"system.functions on ClickHouse {version}")


