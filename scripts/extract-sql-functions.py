#!/usr/bin/env python3
"""Regenerate the built-in SQL function catalogs under crates/blanco/src/sql/functions/.

Each dialect is pulled from a live server in docker-compose.yml, using only the
standard library plus the client each container already ships:

    postgres    psql (host binary) against postgrestestdb_ssl on 127.0.0.1:5488
                pg_catalog.pg_proc, filtered down to user-facing functions
    mysql       `docker exec` into the mariadb container: mysql.help_topic
                (the `HELP` tables, which carry a Syntax block per function)
    clickhouse  HTTP interface on 127.0.0.1:8124: system.functions
    sqlite      Python's sqlite3 module: pragma_function_list. SQLite has no
                signature catalog, so sqlite.rs is curated by hand and this
                subcommand only lints it for missing names.

MSSQL has no catalog of built-ins at all, so mssql.rs is curated by hand.

    python3 scripts/extract-sql-functions.py all
    python3 scripts/extract-sql-functions.py postgres
"""

import argparse
import base64
import json
import os
import re
import sqlite3
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "crates", "blanco", "src", "sql", "functions")


# ---------------------------------------------------------------------------
# Output


def rust_str(text):
    """A Rust string literal. Non-ASCII stays raw; Rust source is UTF-8."""
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            continue
        elif ord(ch) < 0x20:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def emit(dialect, entries, source_note):
    """Write `<dialect>.rs` holding a sorted `FUNCTIONS` slice.

    `entries` is a list of dicts with `name`, `parameters` (list of str),
    `return_type` (str) and `documentation` (str, markdown).
    """
    seen = set()
    unique = []
    for entry in entries:
        key = (entry["name"], tuple(entry["parameters"]))
        if key in seen:
            continue
        seen.add(key)
        unique.append(entry)
    # The Rust side binary-searches on the lowercased name, and overloads of one
    # name must be adjacent.
    unique.sort(key=lambda e: (e["name"].lower(), len(e["parameters"]), e["parameters"]))

    path = os.path.join(OUT_DIR, f"{dialect}.rs")
    with open(path, "w") as out:
        out.write(f"// Generated by scripts/extract-sql-functions.py from {source_note}.\n")
        out.write("// Do not edit by hand.\n\n")
        out.write("use super::FunctionSignature;\n\n")
        out.write("#[rustfmt::skip]\npub(super) const FUNCTIONS: &[FunctionSignature] = &[\n")
        for entry in unique:
            params = ", ".join(rust_str(p) for p in entry["parameters"])
            out.write("    FunctionSignature {\n")
            out.write(f"        name: {rust_str(entry['name'])},\n")
            out.write(f"        parameters: &[{params}],\n")
            out.write(f"        return_type: {rust_str(entry['return_type'])},\n")
            out.write(f"        documentation: {rust_str(entry['documentation'])},\n")
            out.write("    },\n")
        out.write("];\n")
    names = {e["name"] for e in unique}
    print(f"{dialect}: {len(unique)} signatures, {len(names)} functions -> {os.path.relpath(path)}")


def split_top_level(text, separators=","):
    """Split on `separators` outside (), [] and quotes."""
    parts, depth, current, quote = [], 0, [], None
    for ch in text:
        if quote:
            current.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "'\"`":
            quote = ch
            current.append(ch)
        elif ch in "([{":
            depth += 1
            current.append(ch)
        elif ch in ")]}":
            depth = max(0, depth - 1)
            current.append(ch)
        elif ch in separators and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
    tail = "".join(current).strip()
    if tail or parts:
        parts.append(tail)
    return [p for p in parts if p]


def trim_paragraphs(text, limit):
    """Keep whole paragraphs up to roughly `limit` characters."""
    if len(text) <= limit:
        return text
    kept, total = [], 0
    for paragraph in text.split("\n\n"):
        if kept and total + len(paragraph) > limit:
            break
        kept.append(paragraph)
        total += len(paragraph) + 2
    return "\n\n".join(kept).rstrip() + "\n\n…"


def parse_call_syntax(syntax):
    """`name(a, b[, c])` -> (name, ["a", "b", "[, c]"]) or None."""
    match = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\((.*)\)\s*$", syntax, re.S)
    if not match:
        return None
    name, inner = match.group(1), match.group(2).strip()
    return name, split_top_level(inner) if inner else []


